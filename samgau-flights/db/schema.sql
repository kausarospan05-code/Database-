DROP VIEW  IF EXISTS v_booking_details, v_flight_availability CASCADE;
DROP TABLE IF EXISTS PROMO_REDEMPTION, PROMO_CODE, PAYMENT, BAGGAGE, BOOKING, APP_USER, FLIGHT, SEAT, PAYMENT_METHOD,
                     AIRCRAFT, AIRLINE, GATE, AIRPORT, PASSENGER CASCADE;

-- ---------- reference tables ----------

CREATE TABLE AIRPORT (
    code        CHAR(3)       PRIMARY KEY,                -- IATA code, e.g. NQZ
    name        VARCHAR(100)  NOT NULL,
    city        VARCHAR(60)   NOT NULL,
    country     VARCHAR(60)   NOT NULL DEFAULT 'Kazakhstan',
    region      VARCHAR(30)   NOT NULL DEFAULT 'Kazakhstan',  -- groups the airport list on the website
    latitude    NUMERIC(8,5)  NOT NULL,
    longitude   NUMERIC(8,5)  NOT NULL,
    utc_offset  NUMERIC(4,2)  NOT NULL DEFAULT 5             -- local time = UTC + offset (hours)
);

CREATE TABLE AIRLINE (
    airline_code CHAR(2)      PRIMARY KEY,                  -- IATA code, e.g. KC, TK
    name         VARCHAR(50)  NOT NULL UNIQUE,
    country      VARCHAR(60)  NOT NULL,
    hub          CHAR(3)      REFERENCES AIRPORT(code)      -- home airport
);

CREATE TABLE GATE (
    gate_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gate_number  VARCHAR(10)  NOT NULL,
    terminal     VARCHAR(20)  NOT NULL,
    airport_code CHAR(3)      NOT NULL REFERENCES AIRPORT(code) ON DELETE CASCADE,
    UNIQUE (airport_code, gate_number)
);

CREATE TABLE AIRCRAFT (
    aircraft_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration   VARCHAR(10)  NOT NULL UNIQUE,          -- tail number, e.g. P4-KDA
    model          VARCHAR(50)  NOT NULL,
    manufacturer   VARCHAR(50)  NOT NULL,
    airline        VARCHAR(50)  NOT NULL REFERENCES AIRLINE(name),
    seat_rows      INT          NOT NULL CHECK (seat_rows > 0),
    seat_letters   VARCHAR(10)  NOT NULL,                 -- 'ACDF' 2-2, 'ABCDEF' 3-3, 'ABCDEFGHK' 3-3-3, 'ABCDEFGHJK' 3-4-3
    business_rows  INT          NOT NULL DEFAULT 0 CHECK (business_rows >= 0),
    capacity       INT GENERATED ALWAYS AS (seat_rows * length(seat_letters)) STORED
);

CREATE TABLE PAYMENT_METHOD (
    payment_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method_name  VARCHAR(50)  NOT NULL UNIQUE,
    description  TEXT
);

-- Physical seats of an aircraft. Whether a seat is taken on a given flight
-- comes from BOOKING, not from this table. status = 'Blocked' means the seat
-- is out of service (broken, crew rest) and can never be sold.
CREATE TABLE SEAT (
    seat_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seat_number  VARCHAR(10)  NOT NULL,
    class        VARCHAR(20)  NOT NULL CHECK (class IN ('Economy','Business')),
    status       VARCHAR(20)  NOT NULL DEFAULT 'Available' CHECK (status IN ('Available','Blocked')),
    aircraft_id  INT          NOT NULL REFERENCES AIRCRAFT(aircraft_id) ON DELETE CASCADE,
    UNIQUE (aircraft_id, seat_number)
);

-- ---------- people ----------

CREATE TABLE PASSENGER (
    passenger_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name       VARCHAR(50)  NOT NULL,
    last_name        VARCHAR(50)  NOT NULL,
    email            VARCHAR(100),
    phone            VARCHAR(20),
    document_number  VARCHAR(20),                          -- ID card / passport
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Website login. Each account is linked to its own PASSENGER profile.
CREATE TABLE APP_USER (
    user_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(100) NOT NULL UNIQUE,
    password_hash  VARCHAR(200) NOT NULL,
    passenger_id   INT          NOT NULL UNIQUE REFERENCES PASSENGER(passenger_id) ON DELETE CASCADE,
    role           VARCHAR(20)  NOT NULL DEFAULT 'customer' CHECK (role IN ('customer','admin')),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------- operations ----------

CREATE TABLE FLIGHT (
    flight_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_number   VARCHAR(20)   NOT NULL,
    airline         VARCHAR(50)   NOT NULL REFERENCES AIRLINE(name),
    origin          CHAR(3)       NOT NULL REFERENCES AIRPORT(code),
    destination     CHAR(3)       NOT NULL REFERENCES AIRPORT(code),
    departure_time  TIMESTAMP     NOT NULL,                -- local time at the origin airport
    arrival_time    TIMESTAMP     NOT NULL,                -- local time at the destination airport
    departure_utc   TIMESTAMP     NOT NULL,                -- the same moments in UTC, used for durations
    arrival_utc     TIMESTAMP     NOT NULL,                -- and for checking whether a flight has departed
    price           NUMERIC(10,2) NOT NULL CHECK (price > 0),          -- Economy fare
    business_price  NUMERIC(10,2) NOT NULL CHECK (business_price > 0), -- Business fare
    status          VARCHAR(20)   NOT NULL DEFAULT 'Scheduled'
                    CHECK (status IN ('Scheduled','Delayed','Departed','Arrived','Cancelled')),
    gate_id         INT REFERENCES GATE(gate_id) ON DELETE SET NULL,
    aircraft_id     INT REFERENCES AIRCRAFT(aircraft_id) ON DELETE SET NULL,
    CHECK (arrival_utc > departure_utc),
    CHECK (origin <> destination),
    UNIQUE (flight_number, departure_time)
);

-- One row = one passenger on one flight in one seat.
-- Rows sharing a booking_ref were bought together (one checkout).
CREATE TABLE BOOKING (
    booking_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_ref   CHAR(6)       NOT NULL,                  -- PNR shown to the customer
    booking_date  DATE          NOT NULL DEFAULT CURRENT_DATE,
    status        VARCHAR(20)   NOT NULL DEFAULT 'Confirmed'
                  CHECK (status IN ('Confirmed','Pending','Cancelled')),
    passenger_id  INT REFERENCES PASSENGER(passenger_id) ON DELETE CASCADE,
    flight_id     INT REFERENCES FLIGHT(flight_id) ON DELETE CASCADE,
    seat_id       INT REFERENCES SEAT(seat_id) ON DELETE SET NULL,
    user_id       INT REFERENCES APP_USER(user_id) ON DELETE SET NULL,   -- who paid
    payment_id    INT REFERENCES PAYMENT_METHOD(payment_id) ON DELETE SET NULL,
    fare          NUMERIC(10,2) NOT NULL DEFAULT 0,        -- ticket price at time of booking
    total_price   NUMERIC(10,2) NOT NULL DEFAULT 0,        -- fare + baggage
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE BAGGAGE (
    baggage_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    weight_kg   NUMERIC(5,2)  NOT NULL CHECK (weight_kg > 0 AND weight_kg <= 40),
    price       NUMERIC(8,2)  NOT NULL CHECK (price >= 0),
    booking_id  INT REFERENCES BOOKING(booking_id) ON DELETE CASCADE,
    payment_id  INT REFERENCES PAYMENT_METHOD(payment_id) ON DELETE SET NULL
);

-- One row per checkout. Demo payments: only the card brand and last 4 digits are kept.
CREATE TABLE PAYMENT (
    transaction_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_ref    CHAR(6)       NOT NULL,                 -- the booking this payment is for
    user_id        INT REFERENCES APP_USER(user_id) ON DELETE SET NULL,
    payment_id     INT REFERENCES PAYMENT_METHOD(payment_id),
    amount         NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    currency       CHAR(3)       NOT NULL DEFAULT 'KZT',
    status         VARCHAR(20)   NOT NULL CHECK (status IN ('Paid','Pending','Refunded','Cancelled')),
    card_brand     VARCHAR(20),
    card_last4     CHAR(4),
    payer_phone    VARCHAR(20),                            -- Kaspi Pay
    auth_code      VARCHAR(12),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ
);
CREATE INDEX ix_payment_ref  ON PAYMENT (booking_ref);
CREATE INDEX ix_payment_user ON PAYMENT (user_id);

-- ---------- integrity rules ----------

-- A seat can be sold only once per flight (cancelled bookings free it again).
CREATE UNIQUE INDEX ux_booking_flight_seat ON BOOKING (flight_id, seat_id) WHERE status <> 'Cancelled';

-- The seat must belong to the aircraft that operates the flight, and must not be blocked.
CREATE OR REPLACE FUNCTION fn_check_booking_seat() RETURNS trigger AS $$
BEGIN
    IF NEW.seat_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM FLIGHT f JOIN SEAT s ON s.aircraft_id = f.aircraft_id
        WHERE f.flight_id = NEW.flight_id AND s.seat_id = NEW.seat_id AND s.status = 'Available'
    ) THEN
        RAISE EXCEPTION 'Seat % is not available on flight %', NEW.seat_id, NEW.flight_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_booking_seat
BEFORE INSERT OR UPDATE OF seat_id, flight_id ON BOOKING
FOR EACH ROW EXECUTE FUNCTION fn_check_booking_seat();

