-- ---------- views ----------

-- Seats left per class for every flight.
CREATE VIEW v_flight_availability AS
SELECT f.flight_id,
       COUNT(s.seat_id) FILTER (WHERE s.class = 'Economy'  AND s.status = 'Available') AS economy_total,
       COUNT(s.seat_id) FILTER (WHERE s.class = 'Business' AND s.status = 'Available') AS business_total,
       COUNT(s.seat_id) FILTER (WHERE s.class = 'Economy'  AND s.status = 'Available' AND b.booking_id IS NULL) AS economy_left,
       COUNT(s.seat_id) FILTER (WHERE s.class = 'Business' AND s.status = 'Available' AND b.booking_id IS NULL) AS business_left
FROM FLIGHT f
JOIN SEAT s ON s.aircraft_id = f.aircraft_id
LEFT JOIN BOOKING b ON b.flight_id = f.flight_id AND b.seat_id = s.seat_id AND b.status <> 'Cancelled'
GROUP BY f.flight_id;

-- Everything about a booking row in one place (handy in pgAdmin and for reports).
CREATE VIEW v_booking_details AS
SELECT b.booking_id, b.booking_ref, b.booking_date, b.status, b.user_id,
       p.passenger_id, p.first_name, p.last_name, p.email,
       f.flight_id, f.flight_number, f.airline, f.origin, f.destination,
       f.departure_time, f.arrival_time,
       s.seat_number, s.class AS seat_class,
       g.gate_number, g.terminal,
       a.model AS aircraft_model, a.registration,
       pm.method_name AS payment_method,
       b.fare, b.total_price,
       COALESCE((SELECT SUM(bg.weight_kg) FROM BAGGAGE bg WHERE bg.booking_id = b.booking_id), 0) AS baggage_kg
FROM BOOKING b
JOIN PASSENGER p        ON p.passenger_id = b.passenger_id
JOIN FLIGHT f           ON f.flight_id    = b.flight_id
LEFT JOIN SEAT s        ON s.seat_id      = b.seat_id
LEFT JOIN GATE g        ON g.gate_id      = f.gate_id
LEFT JOIN AIRCRAFT a    ON a.aircraft_id  = f.aircraft_id
LEFT JOIN PAYMENT_METHOD pm ON pm.payment_id = b.payment_id;
