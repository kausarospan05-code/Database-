-- What each checkout paid after the discount (PAYMENT.amount is the amount actually charged)
ALTER TABLE PAYMENT ADD COLUMN IF NOT EXISTS promo_code VARCHAR(20);
ALTER TABLE PAYMENT ADD COLUMN IF NOT EXISTS discount   NUMERIC(12,2) NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS PROMO_CODE (
    code             VARCHAR(20)   PRIMARY KEY
                     CHECK (code = upper(code) AND code ~ '^[A-Z0-9_-]{3,20}$'),
    description      VARCHAR(120),
    discount_percent INT           CHECK (discount_percent BETWEEN 1 AND 90),   -- e.g. 10 = 10% off …
    discount_amount  NUMERIC(10,2) CHECK (discount_amount > 0),                 -- … or a fixed amount in ₸
    min_total        NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (min_total >= 0),   -- smallest booking it works on
    valid_from       DATE          NOT NULL DEFAULT CURRENT_DATE,
    valid_until      DATE          NOT NULL,                                    -- expiry date (inclusive)
    max_uses         INT           CHECK (max_uses > 0),                        -- total uses; NULL = unlimited
    used_count       INT           NOT NULL DEFAULT 0,
    per_user_limit   INT           NOT NULL DEFAULT 1 CHECK (per_user_limit > 0),
    active           BOOLEAN       NOT NULL DEFAULT TRUE,                       -- admin can switch a code off
    created_by       INT           REFERENCES APP_USER(user_id) ON DELETE SET NULL,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CHECK ((discount_percent IS NULL) <> (discount_amount IS NULL)),            -- exactly one kind of discount
    CHECK (valid_until >= valid_from),
    CHECK (used_count >= 0 AND (max_uses IS NULL OR used_count <= max_uses))    -- can never go over the limit
);

-- One row each time a code is used on a booking.
CREATE TABLE IF NOT EXISTS PROMO_REDEMPTION (
    redemption_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(20)   NOT NULL REFERENCES PROMO_CODE(code) ON UPDATE CASCADE,
    user_id       INT           REFERENCES APP_USER(user_id) ON DELETE SET NULL,
    booking_ref   CHAR(6)       NOT NULL,
    discount      NUMERIC(12,2) NOT NULL CHECK (discount >= 0),
    redeemed_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    UNIQUE (code, booking_ref)
);
CREATE INDEX IF NOT EXISTS ix_redemption_user ON PROMO_REDEMPTION (user_id, code);

-- ---------------------------------------------------------------------
--  fn_promo_check(code, user, total): can this user use this code on a
--  booking of this total? Returns ok + a message + the discount in ₸.
--  The website calls it both for the "Apply" button and when paying.
--  Try it in pgAdmin:  SELECT * FROM fn_promo_check('STUDENT10', 1, 120000);
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_promo_check(p_code TEXT, p_user INT, p_total NUMERIC)
RETURNS TABLE (ok BOOLEAN, message TEXT, discount NUMERIC) AS $$
DECLARE
    pc   PROMO_CODE%ROWTYPE;
    mine INT;
BEGIN
    SELECT * INTO pc FROM PROMO_CODE WHERE code = upper(trim(p_code));
    IF NOT FOUND THEN
        RETURN QUERY SELECT false, 'This promo code does not exist'::text, 0::numeric; RETURN;
    END IF;
    IF NOT pc.active THEN
        RETURN QUERY SELECT false, 'This promo code is no longer active'::text, 0::numeric; RETURN;
    END IF;
    IF CURRENT_DATE < pc.valid_from THEN
        RETURN QUERY SELECT false, 'This promo code starts on ' || to_char(pc.valid_from, 'DD Mon YYYY'), 0::numeric; RETURN;
    END IF;
    IF CURRENT_DATE > pc.valid_until THEN
        RETURN QUERY SELECT false, 'This promo code expired on ' || to_char(pc.valid_until, 'DD Mon YYYY'), 0::numeric; RETURN;
    END IF;
    IF pc.max_uses IS NOT NULL AND pc.used_count >= pc.max_uses THEN
        RETURN QUERY SELECT false, 'This promo code has reached its usage limit'::text, 0::numeric; RETURN;
    END IF;
    SELECT count(*) INTO mine FROM PROMO_REDEMPTION r WHERE r.code = pc.code AND r.user_id = p_user;
    IF mine >= pc.per_user_limit THEN
        RETURN QUERY SELECT false, 'You have already used this promo code'::text, 0::numeric; RETURN;
    END IF;
    IF p_total < pc.min_total THEN
        RETURN QUERY SELECT false, 'This code needs a booking of at least ' || to_char(pc.min_total, 'FM999G999G999') || ' ₸', 0::numeric; RETURN;
    END IF;
    RETURN QUERY SELECT true, COALESCE(pc.description, pc.code)::text,
        LEAST(p_total, COALESCE(pc.discount_amount, round(p_total * pc.discount_percent / 100.0)));
END $$ LANGUAGE plpgsql STABLE;

